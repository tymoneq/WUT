function Q = g17(f,c,d)
    % Authors: C.F. Gauss, P.K. i ...
    % 18-point Gauss-Legendre integration rule.
    %     f - function handle
    %   c,d - interval endpoints
    
    % Vector of the quadrature nodes for the interval [-1,1]
    x = [ -9.9156516842093094673e-01; -9.5582394957139775518e-01;
          -8.9260246649755573921e-01; -8.0370495897252311568e-01;
          -6.9168704306035320787e-01; -5.5977083107394753461e-01;
          -4.1175116146284264604e-01; -2.5188622569150550959e-01;
          -8.4775013041735301242e-02;  8.4775013041735301242e-02;
           2.5188622569150550959e-01;  4.1175116146284264604e-01;
           5.5977083107394753461e-01;  6.9168704306035320787e-01;
           8.0370495897252311568e-01;  8.9260246649755573921e-01;
           9.5582394957139775518e-01;  9.9156516842093094673e-01 ];
    
    % Vector of the quadrature coefficients for the interval [-1,1]
    A = [  2.1616013526483310313e-02;  4.9714548894969796453e-02;
           7.6425730254889056529e-02;  1.0094204410628716556e-01;
           1.2255520671147846018e-01;  1.4064291467065065120e-01;
           1.5468467512626524493e-01;  1.6427648374583272299e-01;
           1.6914238296314359184e-01;  1.6914238296314359184e-01;
           1.6427648374583272299e-01;  1.5468467512626524493e-01;
           1.4064291467065065120e-01;  1.2255520671147846018e-01;
           1.0094204410628716556e-01;  7.6425730254889056529e-02;
           4.9714548894969796453e-02;  2.1616013526483310313e-02 ];
    
    % Should be completed by a student ;)
    Q = (d-c)/2;
    B = A;
    B = B .* f((d-c)/2 .* x + (c+d)/2);
    suma = sum(B);
    Q = Q*suma;
end
   